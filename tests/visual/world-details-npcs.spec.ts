import { test, expect } from '@playwright/test';
import { getTimestamp } from '@/lib/utils';

/**
 * World detail NPCs section — single-theme (default DS1).
 *
 * DS coverage (#1264): this spec verifies NPC *content* (portrait images when
 * available, initials fallback when missing), not theme layout. The world detail
 * surface is covered across DS1/DS2/DS3 by tests/visual/world-detail-themes.spec.ts.
 */

const GET_TIMESTAMP_SOURCE = getTimestamp.toString();
const WORLD_ID = 'world-npcs-playwright';
const NPC_WITH_PORTRAIT = 'npc-elara';
const NPC_NO_PORTRAIT = 'npc-thorgrim';

const SEED_PAYLOAD = {
  world: {
    id: WORLD_ID,
    name: 'Test Fantasy World',
    description: 'A world for testing NPC portrait displays',
    genre: 'fantasy',
  },
  npcs: [
    {
      id: NPC_WITH_PORTRAIT,
      name: 'Elara Moonwhisper',
      description: 'A mysterious elven ranger with silver hair',
      // Mock avatar URL (would be generated by portrait service in production)
      avatarUrl: 'https://api.dicebear.com/7.x/avataaars/svg?seed=elara',
    },
    {
      id: NPC_NO_PORTRAIT,
      name: 'Thorgrim Ironforge',
      description: 'A gruff dwarven blacksmith',
      // No avatarUrl - should show initials
      avatarUrl: undefined,
    },
  ],
};

test.describe('World details NPC portraits', () => {
  test('shows NPC portraits when available and initials fallback when not', async ({
    page,
    baseURL,
  }) => {
    await page.addInitScript(
      async ({ getTimestampSource, seed }) => {
        const instantiateGetTimestamp = (source: string) =>
          new Function(`return (${source});`)() as () => string;
        const getTs = instantiateGetTimestamp(getTimestampSource);
        const now = getTs();
        const dbName = 'narraitor-state';
        const storeName = 'narraitor-store';

        function put(key: string, value: unknown): Promise<void> {
          return new Promise((resolve) => {
            const open = indexedDB.open(dbName, 1);
            open.onupgradeneeded = () => {
              const db = open.result;
              if (!db.objectStoreNames.contains(storeName)) {
                db.createObjectStore(storeName);
              }
            };
            open.onsuccess = () => {
              const db = open.result;
              const tx = db.transaction(storeName, 'readwrite');
              tx.objectStore(storeName).put({ id: key, value }, key);
              tx.oncomplete = () => resolve();
              tx.onerror = () => resolve();
            };
            open.onerror = () => resolve();
          });
        }

        const worldPersist = {
          state: {
            worlds: {
              [seed.world.id]: {
                ...seed.world,
                attributes: [],
                skills: [],
                derivedStats: [],
                settings: {
                  maxAttributes: 6,
                  maxSkills: 10,
                  attributePointPool: 27,
                  skillPointPool: 40,
                },
                createdAt: now,
                updatedAt: now,
              },
            },
            entities: {
              [seed.world.id]: {
                ...seed.world,
                attributes: [],
                skills: [],
                derivedStats: [],
                settings: {
                  maxAttributes: 6,
                  maxSkills: 10,
                  attributePointPool: 27,
                  skillPointPool: 40,
                },
                createdAt: now,
                updatedAt: now,
              },
            },
            worldStates: {
              [seed.world.id]: {
                worldId: seed.world.id,
                version: 1,
                lastModified: now,
                npcRelationships: {},
                majorEvents: [],
                playerCharacterThreads: {},
                characterRelationships: {},
              },
            },
            currentWorldId: seed.world.id,
            currentEntityId: seed.world.id,
            error: null,
            loading: false,
          },
          version: 2,
        } as const;

        const npcEntries = Object.fromEntries(
          seed.npcs.map((npc) => [
            npc.id,
            {
              id: npc.id,
              name: npc.name,
              description: npc.description,
              worldId: seed.world.id,
              avatarUrl: npc.avatarUrl,
              createdAt: now,
              updatedAt: now,
            },
          ])
        );

        const npcPersist = {
          state: {
            npcs: npcEntries,
            entities: npcEntries,
            worldNpcs: {
              [seed.world.id]: seed.npcs.map((n) => n.id),
            },
            currentEntityId: null,
            error: null,
            loading: false,
          },
          version: 2,
        } as const;

        await Promise.all([
          put('narraitor-world-store', worldPersist),
          put('narraitor-npc-store', npcPersist),
        ]);
      },
      { getTimestampSource: GET_TIMESTAMP_SOURCE, seed: SEED_PAYLOAD }
    );

    await page.goto(`${baseURL}/worlds/${WORLD_ID}`, {
      waitUntil: 'domcontentloaded',
    });

    // Wait for the NPC section heading
    await page.waitForSelector('text=NPCs', { timeout: 10000 });

    // Wait for NPCs to be visible
    await expect(page.locator('text=Elara Moonwhisper')).toBeVisible({
      timeout: 10000,
    });
    await expect(page.locator('text=Thorgrim Ironforge')).toBeVisible({
      timeout: 10000,
    });

    // Verify NPC with portrait shows avatar image
    const elaraAvatar = page.locator('img[alt="Elara Moonwhisper"]');
    await expect(elaraAvatar).toBeVisible();

    // Verify NPC without portrait shows initials fallback
    // The initials should be "TI" for Thorgrim Ironforge
    const thorInitials = page.locator('text=TI').first();
    await expect(thorInitials).toBeVisible();

    await expect(page).toHaveScreenshot('world-details-npc-portraits.png', {
      animations: 'disabled',
      fullPage: true,
    });
  });
});
